/**
 * ユーザー入力にmoodタグを付与してプロンプト用テキストを組み立てる
 */
export function buildUserMessage(input: string, moodTag?: string): string {
  if (moodTag) {
    return `[mood: ${moodTag}]\n${input}`;
  }
  return input;
}

/**
 * AI応答から「小さな一歩」セクションを抽出する
 */
export function extractSmallAction(response: string): string | undefined {
  const match = response.split("### 小さな一歩");
  if (match.length < 2) return undefined;

  // 「### 小さな一歩」以降のテキストから、次の見出し（### ）までを取得
  const actionText = match[1].split("###")[0].trim();
  // マークダウン記法を除去して純粋なテキストにする
  return actionText.replace(/^[\s\-\*]+/, "").trim() || undefined;
}
